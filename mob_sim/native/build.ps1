param(
    [string]$Toolchain = '',
    [Parameter(Mandatory=$true)][string]$Interface,
    [string]$Zig = ''
)
# Builds and tests the engine-free core, then links the Godot extension into mob_sim/bin.
$ErrorActionPreference = 'Stop'
$native = $PSScriptRoot
$bin = Join-Path (Split-Path $native -Parent) 'bin'
$driverArgs = @()
if ($Zig) {
    $cc = (Resolve-Path -LiteralPath $Zig).Path
    $driverArgs = @('cc', '-target', 'x86_64-windows-gnu')
} elseif ($Toolchain) {
    $cc = Join-Path $Toolchain 'bin\x86_64-w64-mingw32-clang.exe'
} else {
    throw 'Supply -Toolchain with an llvm-mingw directory, or -Zig with a zig.exe path.'
}
if (-not (Test-Path -LiteralPath (Join-Path $Interface 'gdextension_interface.h'))) {
    throw 'Interface must contain the header generated by Godot --dump-gdextension-interface.'
}
$flags = @('-std=c11', '-Wall', '-Wextra', '-Werror', '-Wno-cast-function-type-mismatch', '-O2', '-fno-math-errno', '-ffp-contract=off')
$core = @('mob_nav.c', 'mob_policy.c', 'mob_obs.c', 'mob_exec.c', 'mob_decide.c', 'mob_sense.c') | ForEach-Object { Join-Path $native $_ }
New-Item -ItemType Directory -Force $bin | Out-Null

$test = Join-Path $bin 'mob_nav_test.exe'
& $cc @driverArgs @flags @core (Join-Path $native 'mob_nav_test.c') -o $test
if ($LASTEXITCODE -ne 0) { throw 'Core test build failed.' }
& $test
if ($LASTEXITCODE -ne 0) { throw 'Core tests failed.' }

$dll = Join-Path $bin 'mob_nav.dll'
& $cc @driverArgs @flags -shared -I $Interface @core (Join-Path $native 'mob_nav_gdextension.c') -o $dll
if ($LASTEXITCODE -ne 0) { throw 'Extension build failed.' }
"Built $dll"
